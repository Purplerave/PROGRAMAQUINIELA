def validate_rows(rows: list[list[str]], division: str) -> None:
    """Comprueba la transcripción contra el esquema del feed nuevo."""
    date_re = re.compile(r"^\d{2}/\d{2}/2026$")
    for idx, row in enumerate(rows, start=1):
        assert len(row) == len(NEW_FEED_COLUMNS), (
            f"{division} fila {idx}: {len(row)} campos, se esperaban {len(NEW_FEED_COLUMNS)}"
        )
        data = dict(zip(NEW_FEED_COLUMNS, row))
        assert date_re.fullmatch(data["Date"]), f"{division} fila {idx}: Date={data['Date']!r}"
        assert data["FTR"] in {"H", "D", "A"}, f"{division} fila {idx}: FTR={data['FTR']!r}"
        assert data["HomeTeam"] and data["AwayTeam"]
        assert int(data["FTHG"]) >= 0 and int(data["FTAG"]) >= 0
        for col in ("AvgH", "AvgD", "AvgA", "B365H", "B365D", "B365A",
                    "MaxH", "MaxD", "MaxA", "BFEH", "BFED", "BFEA"):
            assert float(data[col]) > 1.01, f"{division} fila {idx}: {col}={data[col]!r}"
        overround = sum(1 / float(data[c]) for c in ("AvgH", "AvgD", "AvgA"))
        assert 1.0 <= overround <= 1.12, f"{division} fila {idx}: overround Avg={overround:.4f}"
        # Control de alineación: siempre debe existir un favorito de mercado a
        # cuota razonable (el resultado puede no coincidir con él: sorpresas).
        assert min(float(data["AvgH"]), float(data["AvgD"]), float(data["AvgA"])) <= 2.6, (
            f"{division} fila {idx}: sin favorito claro en Avg"
        )
        # La tripleta de cierre (AvgCH/CD/CA) debe estar completa salvo celda
        # explícitamente vacía en el feed.
        for col in ("AvgCH", "AvgCD", "AvgCA"):
            value = data[col]
            if value:
                assert float(value) > 1.01, f"{division} fila {idx}: {col}={value!r}"


def repo_header() -> list[str]:
    """Cabecera canónica del repositorio (la de SP1_2526.csv)."""
    with (RAW_BASE / "PRIMERA" / "SP1_2526.csv").open(encoding="utf-8-sig", newline="") as handle:
        return list(csv.reader(handle))[0]


def project_rows(rows: list[list[str]], header: list[str]) -> list[list[str]]:
    """Proyecta filas del feed nuevo sobre el esquema del repositorio.

    Las columnas del feed nuevo que no existen en el esquema del repositorio
    (HxG/AxG/PP*/SKB*) se descartan; las del repositorio que el feed nuevo ya
    no publica (BMGM*/CL*/LB*/PS*/P>2.5/PAHH/PCAHH...) quedan vacías.
    """
    by_name = {col: row for col, row in zip(NEW_FEED_COLUMNS, rows)}
    return [by_name.get(col, "") for col in header]


def write_csv(path: Path, header: list[str], rows: list[list[str]]) -> None:
    with path.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.writer(handle, lineterminator="\r\n")
        writer.writerow(header)
        writer.writerows(rows)


def _completed_rows(header: list[str]) -> list[list[str]]:
    """Convierte COMPLETADO_SP1 al esquema del repositorio (resto en blanco)."""
    out = []
    for item in COMPLETADO_SP1:
        out.append([item.get(col, "") for col in header])
    return out


def main() -> None:
    validate_rows(ROWS_SP1, "SP1")
    validate_rows(ROWS_SP2, "SP2")
    header = repo_header()
    sp1_rows = [project_rows(r, header) for r in ROWS_SP1] + _completed_rows(header)
    write_csv(RAW_BASE / "PRIMERA" / "SP1_2627.csv", header, sp1_rows)
    write_csv(RAW_BASE / "SEGUNDA" / "SP2_2627.csv", header, [project_rows(r, header) for r in ROWS_SP2])
    print(f"SP1_2627.csv: {len(ROWS_SP1)} partidos del feed + {len(COMPLETADO_SP1)} completados = {len(sp1_rows)}")
    print(f"SP2_2627.csv: {len(ROWS_SP2)} partidos escritos")


if __name__ == "__main__":
    main()
